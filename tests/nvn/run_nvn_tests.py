"""Star Road Recomp NVN tests (task-12): build, run the unit and GPU tests, write the reports.

usage: python -I tests/nvn/run_nvn_tests.py [--no-build] [--no-present] [--no-cache]
Exit 0 all pass, 1 a test failed, 3 not run (no toolchain or no usable Vulkan device).
Heavy-process rules: one process at a time, BelowNormal priority, 4 minute limit each, killed by PID only.
"""
import os
import subprocess
import sys
import time

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
BUILD = os.environ.get("NVN_BUILD_DIR", r"A:\AI\Recomps\smrpg-work\build\nvn")
CMAKE = os.environ.get("NVN_CMAKE", r"A:\AI\Recomps\tools-ext\cmake-4.5.1-windows-x86_64\bin\cmake.exe")
SDK_BIN = os.environ.get("NVN_LAYER_PATH", r"A:\AI\Recomps\new-pokemon-snap\tools\vulkan_sdk\Bin")
OUT = os.environ.get("NVN_OUT_DIR", r"A:\AI\Recomps\smrpg-work\nvn\gpu_out")
REPORTS = os.path.join(ROOT, "tests", "nvn", "reports")
BELOW_NORMAL = 0x00004000
LIMIT_S = 240


def run(cmd, log_path, cwd, env=None, limit=LIMIT_S):
    """Run one process at BelowNormal priority, capture output to log_path, kill the tree by PID on timeout."""
    start = time.time()
    with open(log_path, "wb") as log:
        p = subprocess.Popen(cmd, cwd=cwd, env=env, stdout=log, stderr=subprocess.STDOUT, creationflags=BELOW_NORMAL)
        try:
            rc = p.wait(timeout=limit)
        except subprocess.TimeoutExpired:
            subprocess.run(["taskkill", "/PID", str(p.pid), "/T", "/F"], capture_output=True)
            rc = 124
    return rc, time.time() - start


def tail(path, n=12):
    with open(path, "r", errors="replace") as f:
        return "".join(line if len(line) <= 260 else line[:257] + "...\n" for line in f.readlines()[-n:])


def main():
    args = sys.argv[1:]
    os.makedirs(REPORTS, exist_ok=True)
    os.makedirs(OUT, exist_ok=True)
    if "--no-build" not in args:
        if not os.path.exists(os.path.join(BUILD, "CMakeCache.txt")):
            rc, _ = run([CMAKE, "-S", os.path.join(ROOT, "runtime", "nvn"), "-B", BUILD, "-G", "MinGW Makefiles",
                         "-DCMAKE_C_COMPILER=clang", "-DCMAKE_CXX_COMPILER=clang++"], os.path.join(REPORTS, "configure.log"), ROOT)
            if rc != 0:
                print("NOT_RUN: cmake configure failed, see tests/nvn/reports/configure.log")
                return 3
        rc, _ = run([CMAKE, "--build", BUILD, "--target", "nvn_unit", "nvn_gpu", "nvn_cache", "--", "-j6"], os.path.join(REPORTS, "build.log"), ROOT, limit=600)
        if rc != 0:
            print("FAIL: build failed, see tests/nvn/reports/build.log")
            return 1
    env = dict(os.environ)
    env["NVN_LAYER_PATH"] = SDK_BIN
    env["NVN_TEST_DIR"] = os.path.join(ROOT, "tests", "nvn")
    test_dir = os.path.join(ROOT, "tests", "nvn")
    results = []
    unit_log = os.path.join(REPORTS, "nvn_unit.txt")
    rc, secs = run([os.path.join(BUILD, "nvn_unit.exe")], unit_log, test_dir, env)
    results.append(("nvn_unit (sizes, proc table, thunk ABI, formats)", rc, secs, unit_log))
    gpu_log = os.path.join(REPORTS, "nvn_gpu.txt")
    gpu_cmd = [os.path.join(BUILD, "nvn_gpu.exe"), "--out", OUT] + (["--no-present"] if "--no-present" in args else [])
    rc, secs = run(gpu_cmd, gpu_log, test_dir, env)
    results.append(("nvn_gpu (clear, textured quad, RGBA4, depth range, sync, copies, hidden window, validation)", rc, secs, gpu_log))
    if "--no-cache" not in args:
        # Shader cache reader (docs/SHADER_CACHE.md section 5): hidden and muted, no window, no audio device.
        env["SDL_AUDIODRIVER"] = "dummy"
        env["SDL_AUDIO_DRIVER"] = "dummy"
        pipe_log = os.path.join(REPORTS, "nvn_cache_pipelines.txt")
        rc, secs = run([os.path.join(BUILD, "nvn_cache.exe"), "--no-sweep", "--out", OUT], pipe_log, test_dir, env)
        results.append(("nvn_cache pipelines (support buffer and c[1] pixel check, 600 real variants built and drawn, validation on)", rc, secs, pipe_log))
        sweep_log = os.path.join(REPORTS, "nvn_cache_sweep.txt")
        rc, secs = run([os.path.join(BUILD, "nvn_cache.exe"), "--sweep-only", "--no-validation", "--out", OUT], sweep_log, test_dir, env)
        results.append(("nvn_cache sweep (every stage program: capability check, shader module, descriptor set layout; vs/fs pairing)", rc, secs, sweep_log))

    worst = 0
    lines = ["# NVN test report (task-12)", "", "Generated by tests/nvn/run_nvn_tests.py. Exit codes: 0 pass, 1 fail, 3 not run.", ""]
    for name, rc, secs, log in results:
        status = {0: "PASS", 3: "NOT_RUN"}.get(rc, "FAIL")
        worst = max(worst, 1 if status == "FAIL" else (3 if status == "NOT_RUN" and worst == 0 else 0))
        lines += [f"## {name}", f"Result: {status} (exit {rc}, {secs:.1f} s)", "", "```", tail(log, 24 if "nvn_cache" in log else 14).rstrip(), "```", ""]
    path = os.path.join(REPORTS, "NVN_TEST_REPORT.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("\n".join(lines[4:]))
    print("report:", path)
    return worst


if __name__ == "__main__":
    sys.exit(main())
