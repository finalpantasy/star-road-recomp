// ASTC block footprints in NVN enum order (0x79..0x86); the sRGB range follows at +14.
static const VkFormat kAstcLinear[14] = {
  VK_FORMAT_ASTC_4x4_UNORM_BLOCK, VK_FORMAT_ASTC_5x4_UNORM_BLOCK, VK_FORMAT_ASTC_5x5_UNORM_BLOCK, VK_FORMAT_ASTC_6x5_UNORM_BLOCK,
  VK_FORMAT_ASTC_6x6_UNORM_BLOCK, VK_FORMAT_ASTC_8x5_UNORM_BLOCK, VK_FORMAT_ASTC_8x6_UNORM_BLOCK, VK_FORMAT_ASTC_8x8_UNORM_BLOCK,
  VK_FORMAT_ASTC_10x5_UNORM_BLOCK, VK_FORMAT_ASTC_10x6_UNORM_BLOCK, VK_FORMAT_ASTC_10x8_UNORM_BLOCK, VK_FORMAT_ASTC_10x10_UNORM_BLOCK,
  VK_FORMAT_ASTC_12x10_UNORM_BLOCK, VK_FORMAT_ASTC_12x12_UNORM_BLOCK};
static const VkFormat kAstcSrgb[14] = {
  VK_FORMAT_ASTC_4x4_SRGB_BLOCK, VK_FORMAT_ASTC_5x4_SRGB_BLOCK, VK_FORMAT_ASTC_5x5_SRGB_BLOCK, VK_FORMAT_ASTC_6x5_SRGB_BLOCK,
  VK_FORMAT_ASTC_6x6_SRGB_BLOCK, VK_FORMAT_ASTC_8x5_SRGB_BLOCK, VK_FORMAT_ASTC_8x6_SRGB_BLOCK, VK_FORMAT_ASTC_8x8_SRGB_BLOCK,
  VK_FORMAT_ASTC_10x5_SRGB_BLOCK, VK_FORMAT_ASTC_10x6_SRGB_BLOCK, VK_FORMAT_ASTC_10x8_SRGB_BLOCK, VK_FORMAT_ASTC_10x10_SRGB_BLOCK,
  VK_FORMAT_ASTC_12x10_SRGB_BLOCK, VK_FORMAT_ASTC_12x12_SRGB_BLOCK};

bool IsDepthFormat(VkFormat f) {
  return f == VK_FORMAT_D16_UNORM || f == VK_FORMAT_X8_D24_UNORM_PACK32 || f == VK_FORMAT_D32_SFLOAT || f == VK_FORMAT_D24_UNORM_S8_UINT ||
         f == VK_FORMAT_D32_SFLOAT_S8_UINT || f == VK_FORMAT_S8_UINT;
}

static bool FormatOk(VkFormat f, VkFormatFeatureFlags need) {
  if (!g_vk.phys) return true;
  VkFormatProperties p;
  g_vk.f.vkGetPhysicalDeviceFormatProperties(g_vk.phys, f, &p);
  return (p.optimalTilingFeatures & need) == need;
}

// Image format for an NVN texture format. ASTC becomes RGBA8 when the GPU cannot sample it (task-11 decodes at upload).
VkFormat VkFormatFromNvn(uint32_t nvnFormat, int* srFmtOut, int* srgbOut, VkImageAspectFlags* aspect) {
  if (aspect) *aspect = VK_IMAGE_ASPECT_COLOR_BIT;
  if (srgbOut) *srgbOut = 0;
  if (srFmtOut) *srFmtOut = 0;
  VkFormat vk = VK_FORMAT_UNDEFINED;
  if (nvnFormat >= NVN_FORMAT_RGBA_ASTC_4x4 && nvnFormat <= NVN_FORMAT_RGBA_ASTC_12x12_SRGB) {
    bool srgb = nvnFormat >= NVN_FORMAT_RGBA_ASTC_4x4_SRGB;
    uint32_t idx = (nvnFormat - NVN_FORMAT_RGBA_ASTC_4x4) % 14;
    if (srgbOut) *srgbOut = srgb;
    VkFormat nat = srgb ? kAstcSrgb[idx] : kAstcLinear[idx];
    if (g_vk.phys && FormatOk(nat, VK_FORMAT_FEATURE_SAMPLED_IMAGE_BIT)) vk = nat;
    else vk = srgb ? VK_FORMAT_R8G8B8A8_SRGB : VK_FORMAT_R8G8B8A8_UNORM;
  } else {
    for (const FEnt& e : kFormats)
      if (e.nvn == nvnFormat) { vk = e.vk; break; }
    if (vk == VK_FORMAT_UNDEFINED) {
      // integer to float vertex-only formats have no texture meaning: treat as the integer form
      if (nvnFormat >= NVN_FORMAT_R8_UI2F && nvnFormat <= NVN_FORMAT_RGB10A2_I2F) return VK_FORMAT_UNDEFINED;
      return VK_FORMAT_UNDEFINED;
    }
    if (nvnFormat == NVN_FORMAT_RGBA8_SRGB || nvnFormat == NVN_FORMAT_RGBX8_SRGB || nvnFormat == NVN_FORMAT_BGRA8_SRGB ||
        nvnFormat == NVN_FORMAT_BGRX8_SRGB || (nvnFormat >= NVN_FORMAT_RGB_DXT1_SRGB && nvnFormat <= NVN_FORMAT_RGBA_DXT5_SRGB) ||
        nvnFormat == NVN_FORMAT_BPTC_UNORM_SRGB)
      if (srgbOut) *srgbOut = 1;
  }
  if (aspect) {
    switch (vk) {
      case VK_FORMAT_D16_UNORM: case VK_FORMAT_X8_D24_UNORM_PACK32: case VK_FORMAT_D32_SFLOAT: *aspect = VK_IMAGE_ASPECT_DEPTH_BIT; break;
      case VK_FORMAT_S8_UINT: *aspect = VK_IMAGE_ASPECT_STENCIL_BIT; break;
      case VK_FORMAT_D24_UNORM_S8_UINT: case VK_FORMAT_D32_SFLOAT_S8_UINT: *aspect = VK_IMAGE_ASPECT_DEPTH_BIT | VK_IMAGE_ASPECT_STENCIL_BIT; break;
      default: break;
    }
  }
  // packed depth formats that a device lacks fall back to 32 bit float
  if (g_vk.phys && IsDepthFormat(vk) && !FormatOk(vk, VK_FORMAT_FEATURE_DEPTH_STENCIL_ATTACHMENT_BIT)) {
    if (vk == VK_FORMAT_D24_UNORM_S8_UINT) vk = VK_FORMAT_D32_SFLOAT_S8_UINT;
    else if (vk == VK_FORMAT_X8_D24_UNORM_PACK32) vk = VK_FORMAT_D32_SFLOAT;
  }
  return vk;
}

uint32_t NvnFormatBytes(uint32_t nvnFormat) {
  for (const FEnt& e : kFormats)
    if (e.nvn == nvnFormat) return e.bytes;
  if (nvnFormat >= NVN_FORMAT_RGBA_ASTC_4x4 && nvnFormat <= NVN_FORMAT_RGBA_ASTC_12x12_SRGB) return 16;
  return 0;
}

// Vertex attribute formats: the integer to float conversions (UI2F, I2F) are scaled formats.
VkFormat VertexFormatFromNvn(uint32_t f, bool* isInt) {
  if (isInt) *isInt = false;
  static const struct { uint32_t base; VkFormat s; VkFormat u; } scaled[] = {
    {NVN_FORMAT_R8_UI2F, VK_FORMAT_R8_SSCALED, VK_FORMAT_R8_USCALED}, {NVN_FORMAT_R16_UI2F, VK_FORMAT_R16_SSCALED, VK_FORMAT_R16_USCALED},
    {NVN_FORMAT_RG8_UI2F, VK_FORMAT_R8G8_SSCALED, VK_FORMAT_R8G8_USCALED}, {NVN_FORMAT_RG16_UI2F, VK_FORMAT_R16G16_SSCALED, VK_FORMAT_R16G16_USCALED},
    {NVN_FORMAT_RGB8_UI2F, VK_FORMAT_R8G8B8_SSCALED, VK_FORMAT_R8G8B8_USCALED}, {NVN_FORMAT_RGB16_UI2F, VK_FORMAT_R16G16B16_SSCALED, VK_FORMAT_R16G16B16_USCALED},
    {NVN_FORMAT_RGBA8_UI2F, VK_FORMAT_R8G8B8A8_SSCALED, VK_FORMAT_R8G8B8A8_USCALED}, {NVN_FORMAT_RGBA16_UI2F, VK_FORMAT_R16G16B16A16_SSCALED, VK_FORMAT_R16G16B16A16_USCALED},
    {NVN_FORMAT_RGB10A2_UI2F, VK_FORMAT_A2B10G10R10_SSCALED_PACK32, VK_FORMAT_A2B10G10R10_USCALED_PACK32}};
  for (auto& s : scaled)
    if (f == s.base) return s.u;
    else if (f == s.base + 1) return s.s;
  if (f == NVN_FORMAT_R32_UI2F || f == NVN_FORMAT_R32_I2F || f == NVN_FORMAT_RG32_UI2F || f == NVN_FORMAT_RG32_I2F || f == NVN_FORMAT_RGB32_UI2F ||
      f == NVN_FORMAT_RGB32_I2F || f == NVN_FORMAT_RGBA32_UI2F || f == NVN_FORMAT_RGBA32_I2F)
    return VK_FORMAT_UNDEFINED;   // no Vulkan equivalent: the pipeline logs and skips the attribute
  VkFormat vk = VkFormatFromNvn(f, nullptr, nullptr, nullptr);
  if (isInt && vk != VK_FORMAT_UNDEFINED) {
    switch (vk) {
      case VK_FORMAT_R8_UINT: case VK_FORMAT_R8_SINT: case VK_FORMAT_R16_UINT: case VK_FORMAT_R16_SINT: case VK_FORMAT_R32_UINT:
      case VK_FORMAT_R32_SINT: case VK_FORMAT_R8G8_UINT: case VK_FORMAT_R8G8_SINT: case VK_FORMAT_R16G16_UINT: case VK_FORMAT_R16G16_SINT:
      case VK_FORMAT_R32G32_UINT: case VK_FORMAT_R32G32_SINT: case VK_FORMAT_R32G32B32_UINT: case VK_FORMAT_R32G32B32_SINT:
      case VK_FORMAT_R8G8B8A8_UINT: case VK_FORMAT_R8G8B8A8_SINT: case VK_FORMAT_R16G16B16A16_UINT: case VK_FORMAT_R16G16B16A16_SINT:
      case VK_FORMAT_R32G32B32A32_UINT: case VK_FORMAT_R32G32B32A32_SINT: *isInt = true; break;
      default: break;
    }
  }
  return vk;
}

// NVN texture swizzle value (ZERO, ONE, R, G, B, A) to Vulkan.
VkComponentSwizzle SwizzleFromNvn(uint32_t s, VkComponentSwizzle identity) {
  switch (s) {
    case NVN_TEXTURE_SWIZZLE_ZERO: return VK_COMPONENT_SWIZZLE_ZERO;
    case NVN_TEXTURE_SWIZZLE_ONE: return VK_COMPONENT_SWIZZLE_ONE;
    case NVN_TEXTURE_SWIZZLE_R: return VK_COMPONENT_SWIZZLE_R;
    case NVN_TEXTURE_SWIZZLE_G: return VK_COMPONENT_SWIZZLE_G;
    case NVN_TEXTURE_SWIZZLE_B: return VK_COMPONENT_SWIZZLE_B;
    case NVN_TEXTURE_SWIZZLE_A: return VK_COMPONENT_SWIZZLE_A;
  }
  return identity;
}

