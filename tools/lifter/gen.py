"""Generators shared by the lifter, the interpreter and the tests (task-5). Our own code.

  ops_gen.h      OP_<name>(fields...) macros from the op table
  interp_gen.inc the interpreter's switch (case IROP_x: OP_x(i->f[k]..., i->i[k]...))
  encode()       32-byte IR record: u16 op, u8 f[10], u32 aux, s64 i[2]
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ops  # noqa: E402

# SMRPG_EXT selects extension modules (comma list of simd_a, simd_b); default both. A worker developing one
# extension runs with its own name only, so another worker's half-written file cannot break its run.
EXT_NAMES = [x for x in os.environ.get("SMRPG_EXT", "simd_a,simd_b").split(",") if x]
for _m in EXT_NAMES:
    try:
        __import__("ops_" + _m)
    except ImportError:
        pass

GEN_DIR = r"A:\AI\Recomps\smrpg-work\build\gen"
CTRL = ["b", "bl", "cbz", "tbz", "bcond", "br", "blr", "ret", "svc", "brk"]
IROP_ID = {n: i for i, n in enumerate(ops.ORDER)}
for _i, _n in enumerate(CTRL):
    IROP_ID["ctl_" + _n] = len(ops.ORDER) + _i
# Append new IDs after the existing control records so old IR images still load.
_legacy_ops = len(ops.ORDER)
import ops_crypto  # noqa: E402,F401
if "ops_simd_b" in sys.modules:
    sys.modules["ops_simd_b"].register_scalar_sat()
for _n in ops.ORDER[_legacy_ops:]:
    IROP_ID[_n] = len(IROP_ID)
IROP_BAD = 0xFFFF
RECORD = struct.Struct("<H10BIqq")


def slots(name):
    """(byte_fields, imm_fields) in spec order."""
    fs = ops.OPS[name]["fields"]
    return [f[0] for f in fs if f[1] != "imm"], [f[0] for f in fs if f[1] == "imm"]


def _s64(v):
    v &= (1 << 64) - 1
    return v - (1 << 64) if v >> 63 else v


def encode(name, f, aux=0):
    if name in CTRL:
        b = [0] * 10
        i = [0, 0]
        if name in ("b", "bl", "bcond"):
            i[0] = _s64(f["target"])
            if name == "bcond":
                b[0] = f["cond"]
        elif name == "cbz":
            b[0], b[1], b[2] = f["rt"], f["sf"], f["nz"]
            i[0] = _s64(f["target"])
        elif name == "tbz":
            b[0], b[1], b[2] = f["rt"], f["bit"], f["nz"]
            i[0] = _s64(f["target"])
        elif name in ("br", "blr", "ret"):
            b[0] = f["rn"]
        else:
            i[0] = f["imm"]
        return RECORD.pack(IROP_ID["ctl_" + name], *b, aux, i[0], i[1])
    bs, ims = slots(name)
    b = [f[x] for x in bs] + [0] * (10 - len(bs))
    i = [_s64(f[x]) for x in ims] + [0] * (2 - len(ims))
    return RECORD.pack(IROP_ID[name], *b, aux, i[0], i[1])


def encode_bad(reason_code=0):
    return RECORD.pack(IROP_BAD, *([0] * 10), reason_code, 0, 0)


def gen_ops_header():
    out = ["/* generated by tools/lifter/gen.py; do not edit */", "#pragma once"]
    with open(os.path.join(os.path.dirname(__file__), "ir_crypto.h"), encoding="ascii") as f:
        out.append(f.read())
    for n in ops.ORDER:
        o = ops.OPS[n]
        params = ", ".join(x[0] for x in o["fields"])
        body = o["body"].replace("\n", " \\\n    ")
        out.append("#define OP_%s(%s) do { %s } while (0)" % (n, params, body))
    out.append("enum { " + ", ".join("IROP_%s" % n for n in IROP_ID) + ", IROP_COUNT };")
    return "\n".join(out) + "\n"


def gen_interp_switch():
    out = []
    for n in ops.ORDER:
        bs, ims = slots(n)
        args = ["i->f[%d]" % k for k in range(len(bs))] + ["i->i[%d]" % k for k in range(len(ims))]
        # keep the spec order of the macro parameters
        order = []
        bi = ii = 0
        for fn, kind, *_ in ops.OPS[n]["fields"]:
            if kind == "imm":
                order.append("i->i[%d]" % ii)
                ii += 1
            else:
                order.append("i->f[%d]" % bi)
                bi += 1
        out.append("case IROP_%s: OP_%s(%s); break;" % (n, n, ", ".join(order)))
    return "\n".join(out) + "\n"


def write_if_changed(path, text):
    """Write text only when it differs, so an unchanged header keeps its timestamp and does not force a rebuild."""
    try:
        with open(path, encoding="utf-8", newline="") as f:
            if f.read() == text:
                return False
    except OSError:
        pass
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text)
    return True


def write_all(d=GEN_DIR):
    os.makedirs(d, exist_ok=True)
    write_if_changed(os.path.join(d, "ops_gen.h"), gen_ops_header())
    write_if_changed(os.path.join(d, "interp_gen.inc"), gen_interp_switch())
    return d


if __name__ == "__main__":
    print(write_all(), len(ops.ORDER), "ops")
