#!/usr/bin/env python3
"""Generate runtime/nvn/nvn_enums.h: the NVN enum value tables (facts about the public NVN C API), read from a
community header (MIT) as data. Only `typedef enum { ... } NVNname;` blocks are taken; nothing else is copied.
Run: python tools/nvngen/gen_enums.py [--header FILE] [--out FILE]"""
import argparse, os, re
HDR = r"A:\AI\Recomps\new-pokemon-snap\tools\ref\totk\runtime\nvn.h"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "runtime", "nvn", "nvn_enums.h")
ap = argparse.ArgumentParser(); ap.add_argument("--header", default=HDR); ap.add_argument("--out", default=OUT)
a = ap.parse_args()
src = open(a.header, encoding="utf-8", errors="replace").read()
blocks = re.findall(r"(?:typedef\s+)?enum\s*(\w*)\s*\{(.*?)\}\s*(\w*)\s*;", src, re.S)
out = ["// Generated by tools/nvngen/gen_enums.py from the public NVN C API enum tables. Do not edit.",
       "#pragma once", "#include <stdint.h>", "namespace nvn {"]
n = 0
for tag, body, name in blocks:
    nm = name or tag
    if not nm.startswith("NVN"): continue
    members = []
    for line in body.split(","):
        line = re.sub(r"//.*", "", line).strip()
        m = re.match(r"(\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)$", line)
        if m and not m.group(1).endswith("_LARGE"): members.append((m.group(1), m.group(2)))
    if not members: continue
    out.append("enum %s : uint32_t {" % nm)
    for k, v in members: out.append("  %s = %s," % (k, v))
    out.append("};"); n += 1
out.append("}  // namespace nvn")
open(a.out, "w", newline="\n").write("\n".join(out) + "\n")
print("enums", n)
